"""Host driver kind `irq_managed` : make the kernel-MANAGED interrupts of disk controllers movable.

Same two callers as the other kinds, so they cannot drift:
  * `node_agent/install-node.sh` (`provision_irq_managed`, new node)  -> `irq_managed.py run`
  * the node agent's generic host-driver job layer                    -> `irq_managed.py state` / `run`
Contract (NODE_AGENT.md §4.6): `state` prints ONE JSON document whose status/code/keys/step ids are
CODES translated by the UI; `run` logs ENGLISH lines and exits 0 (done), 10 (reboot required) or
other (failure). `revert` (not wired to the UI) takes the parameters back out, same exit codes.

Why (measured on dell-1, 2026-11-25): megaraid_sas spreads one MSI-X queue per CPU and lets the
kernel MANAGE them — their affinity cannot be written, so the node agent cannot steer them off a
Dedicated core (`isolation.irq_unmovable`). 25 interrupts/s landed on the Dedicated cores of a
player. Each such driver has a module parameter that turns the queues into ordinary interrupts;
after the reboot the agent steers them like any other (agent >= 0.32.2).

What it does, and nothing else:
  1. for every controller in DRIVERS whose module is loaded, that HAS interrupts in /proc/interrupts
     and whose parameter (/sys/module/<mod>/parameters/<param>) still reads « managed », puts
     `<module>.<param>=<ordinary>` on the kernel command line:
       GRUB          GRUB_CMDLINE_LINUX in /etc/default/grub, then update-grub, then checked in every
                     entry of the 10_linux section of grub.cfg (catches an /etc/default/grub.d override)
       systemd-boot  /etc/kernel/cmdline, then proxmox-boot-tool refresh
     The bootloader is chosen by the TOOL present, exactly as app/mtl.py does (proxmox-boot-tool, else
     update-grub — never by the mere existence of /etc/kernel/cmdline). app/mtl.py owns
     GRUB_CMDLINE_LINUX_DEFAULT (hugepages, isolcpus…); this kind writes GRUB_CMDLINE_LINUX only, so
     neither rewrites the other's tokens. The previous file is kept as <file>.bak.irq_managed.<date>.
  2. NO initramfs rebuild, NO /etc/modprobe.d file: modprobe (kmod) reads `<module>.<param>=` from
     /proc/cmdline when it loads a module — in the initramfs too (Debian's initramfs-tools ships kmod's
     modprobe; Documentation/admin-guide/kernel-parameters.rst, « modprobe looks through the kernel
     command line »). One place to write, one to read back, one to take back; every installed kernel,
     present or future, gets it.
The node is never rebooted: exit 10, the operator reboots from the node card.

Not handled, said in `state` (`others`): NVMe. Its queues are always managed and no parameter changes
that; a queue's interrupt fires only for I/O issued from its CPU — the Dedicated container's own I/O.
`isolcpus=managed_irq,<cpus>` only helps a queue whose mask also holds a housekeeping CPU, needs a
static CPU list at boot (Dedicated cores are given out at run time) and `isolcpus=` belongs to
app/mtl.py: not written here.

Only the standard library. `decide` is pure; tests replay facts (tests/verif_irq_managed_driver.py).
"""
import json
import os
import re
import shutil
import subprocess
import sys
import time

KIND = "irq_managed"
SCRIPT_VERSION = "1.0.0"
EXIT_OK, EXIT_REBOOT = 0, 10

# module → (irq name prefixes in /proc/interrupts, parameter, value meaning « managed », value making
# the queues ordinary). Kept in step with app/node_aptitude.py MANAGED_IRQ_DRIVERS (guarded).
DRIVERS = {
    "megaraid_sas": (("megasas",), "smp_affinity_enable", "1", "0"),
    "mpt3sas": (("mpt3sas", "mpt2sas"), "smp_affinity_enable", "1", "0"),
    "smartpqi": (("smartpqi",), "disable_managed_interrupts", "0", "1"),
}
# Always managed, no parameter: reported, never acted upon.
OTHERS = {"nvme": ("nvme",)}

GRUB_DEFAULTS = "/etc/default/grub"
GRUB_CFG = "/boot/grub/grub.cfg"
KERNEL_CMDLINE = "/etc/kernel/cmdline"

PROBES = {
    "cmdline": "cat /proc/cmdline",
    # Same rule as app/mtl.py (`@@BOOTLOADER`): the tool decides.
    "bootloader": "(proxmox-boot-tool status >/dev/null 2>&1 && echo systemd-boot) || "
                  "(command -v update-grub >/dev/null 2>&1 && echo grub) || echo unknown",
    # What update-grub will really use: /etc/default/grub then /etc/default/grub.d/*.cfg, sourced.
    "grub_effective": "( . %s; for f in /etc/default/grub.d/*.cfg; do [ -e \"$f\" ] && . \"$f\"; done; "
                      "echo \"L=$GRUB_CMDLINE_LINUX\"; echo \"D=$GRUB_CMDLINE_LINUX_DEFAULT\" ) 2>/dev/null "
                      "|| true" % GRUB_DEFAULTS,
    # The linux lines generated by 10_linux (every installed kernel, recovery included).
    "grub_cfg": "awk '/BEGIN \\/etc\\/grub.d\\/10_linux/{s=1} /END \\/etc\\/grub.d\\/10_linux/{s=0} "
                "s && $1==\"linux\"' %s 2>/dev/null || true" % GRUB_CFG,
    "kernel_cmdline": "cat %s 2>/dev/null || true" % KERNEL_CMDLINE,
    "params": "for m in %s; do if [ -d /sys/module/$m ]; then for p in /sys/module/$m/parameters/*; do "
              "[ -r \"$p\" ] && echo \"$m $(basename $p) $(cat $p 2>/dev/null)\"; done; echo \"$m -loaded- 1\"; "
              "fi; done" % " ".join(sorted(set(DRIVERS) | set(OTHERS))),
    "irqs": "awk '$1 ~ /^[0-9]+:$/ {print $NF}' /proc/interrupts",
}


def _sh(cmd, timeout=60):
    try:
        p = subprocess.run(["bash", "-c", cmd], capture_output=True, text=True, timeout=timeout)
        return p.returncode, (p.stdout or "") + ("" if p.returncode == 0 else (p.stderr or ""))
    except Exception as e:                              # noqa: BLE001
        return 255, str(e)


def live_probe(name):
    return _sh(PROBES[name])


def token(module):
    _p, param, _m, ordinary = DRIVERS[module]
    return "%s.%s=%s" % (module, param, ordinary)


def key_of(tok):
    return tok.split("=", 1)[0]


def gather_facts(probe=live_probe):
    f = {"cmdline": (probe("cmdline")[1] or "").split()}
    bl = (probe("bootloader")[1] or "").strip()
    f["bootloader"] = bl if bl in ("grub", "systemd-boot") else None
    eff = {}
    for line in (probe("grub_effective")[1] or "").splitlines():
        if line[:2] in ("L=", "D="):
            eff[line[0]] = line[2:].split()
    f["grub_linux"], f["grub_default"] = eff.get("L", []), eff.get("D", [])
    f["grub_cfg"] = [ln.split() for ln in (probe("grub_cfg")[1] or "").splitlines() if ln.strip()]
    f["kernel_cmdline"] = (probe("kernel_cmdline")[1] or "").split()
    params, loaded = {}, set()
    for line in (probe("params")[1] or "").splitlines():
        p = line.split(None, 2)
        if len(p) < 2:
            continue
        if p[1] == "-loaded-":
            loaded.add(p[0])
        else:
            params[(p[0], p[1])] = p[2].strip() if len(p) > 2 else ""
    f["loaded"] = loaded
    names = (probe("irqs")[1] or "").split()
    f["irq_count"] = {}
    for mod, prefixes in [(m, v[0]) for m, v in DRIVERS.items()] + list(OTHERS.items()):
        n = sum(1 for x in names if x.startswith(prefixes))
        if n:
            f["irq_count"][mod] = n
    f["params"] = {m: params.get((m, DRIVERS[m][1])) for m in DRIVERS if m in loaded}
    return f


def _plan(status, code, **kw):
    p = {"status": status, "code": code, "params": {}, "steps": [], "tokens": [], "needs_reboot": False}
    p.update(kw)
    return p


def controllers(f):
    """[(module, value, state)] of the controllers present (module loaded AND interrupts):
    state = managed | ordinary | unknown (parameter unreadable)."""
    out = []
    for m, (_pre, _param, managed, ordinary) in sorted(DRIVERS.items()):
        if m not in f["loaded"] or not f["irq_count"].get(m):
            continue
        v = f["params"].get(m)
        st = "managed" if v == managed else "ordinary" if v == ordinary else "unknown"
        out.append((m, v, st))
    return out


def pending_tokens(f):
    """The command line the NEXT boot gets, as configured (not as generated)."""
    if f["bootloader"] == "systemd-boot":
        return list(f["kernel_cmdline"])
    return list(f["grub_linux"]) + list(f["grub_default"])


def configured_tokens(f):
    """Where THIS kind writes: /etc/kernel/cmdline, or GRUB_CMDLINE_LINUX (never _DEFAULT, app/mtl.py's).
    A token found only in _DEFAULT is moved: it would miss the recovery entries."""
    if f["bootloader"] == "systemd-boot":
        return list(f["kernel_cmdline"])
    return list(f["grub_linux"])


def decide(f):
    ctrls = controllers(f)
    others = sorted(m for m in OTHERS if m in f["loaded"] and f["irq_count"].get(m))
    base = {"others": ",".join(others) or "-"}
    todo = [m for m, _v, st in ctrls if st == "managed"]
    unknown = [m for m, _v, st in ctrls if st == "unknown"]
    if not ctrls:
        return _plan("ok", "nvme_only" if others else "none", params=base)
    if not todo:
        if unknown:
            return _plan("refused", "param_unreadable", params=dict(base, modules=",".join(unknown)))
        return _plan("ok", "active", params=dict(base, modules=",".join(m for m, _v, _s in ctrls)))
    toks = [token(m) for m in todo]
    params = dict(base, modules=",".join(todo), tokens=" ".join(toks))
    # On the running command line and still managed: the driver ignored it — writing it again would
    # change nothing, a reboot would not either.
    ignored = [t for t in toks if t in f["cmdline"]]
    if ignored:
        return _plan("refused", "not_honoured", params=dict(params, tokens=" ".join(ignored)), tokens=toks)
    if not f["bootloader"]:
        return _plan("refused", "no_bootloader", params=params, tokens=toks)
    pend = configured_tokens(f)
    missing = [t for t in toks if t not in pend]
    if missing:
        return _plan("install", "apply", params=params, tokens=toks, needs_reboot=True,
                     steps=["cmdline", "bootloader"])
    if f["bootloader"] == "grub" and (not f["grub_cfg"] or any(t not in ln for ln in f["grub_cfg"] for t in toks)):
        return _plan("install", "regenerate", params=params, tokens=toks, needs_reboot=True,
                     steps=["bootloader"])
    return _plan("pending_reboot", "pending_reboot", params=params, tokens=toks)


def rows_for_ui(f, plan):
    rows = []
    for m, v, st in controllers(f):
        rows.append({"key": "controller", "value": "%s, %d IRQ, %s=%s" % (
            m, f["irq_count"].get(m, 0), DRIVERS[m][1], "?" if v is None else v)})
    for m in sorted(OTHERS):
        if m in f["loaded"] and f["irq_count"].get(m):
            rows.append({"key": "others", "value": "%s (%d IRQ)" % (m, f["irq_count"][m])})
    rows.append({"key": "bootloader", "value": f["bootloader"] or "?"})
    mine = [t for t in pending_tokens(f) if key_of(t) in {key_of(token(m)) for m in DRIVERS}]
    rows.append({"key": "configured", "value": " ".join(mine) or "-"})
    live = [t for t in f["cmdline"] if key_of(t) in {key_of(token(m)) for m in DRIVERS}]
    rows.append({"key": "running", "value": " ".join(live) or "-"})
    return rows


def state(probe=live_probe):
    f = gather_facts(probe)
    plan = decide(f)
    f2 = dict(f, loaded=sorted(f["loaded"]), grub_cfg=len(f["grub_cfg"]))
    return {"kind": KIND, "version": SCRIPT_VERSION, "status": plan["status"], "plan": plan,
            "rows": rows_for_ui(f, plan), "can_run": plan["status"] == "install", "facts": f2}


# ─── edits (pure, on text) ─────────────────────────────────────────────────────────────────────────
_LINE = re.compile(r'^(GRUB_CMDLINE_LINUX(?:_DEFAULT)?)=(?:"([^"\n]*)"|\'([^\'\n]*)\'|([^\s"\'#]*))\s*(#.*)?$')


class StepError(Exception):
    pass


def edit_tokens(tokens, add=(), drop_keys=()):
    """Token list without the `drop_keys` (any value) and without the keys of `add`, then `add`."""
    keys = set(drop_keys) | {key_of(t) for t in add}
    out = [t for t in tokens if key_of(t) not in keys]
    return out + [t for t in add]


def edit_grub_defaults(text, add=(), drop_keys=()):
    """/etc/default/grub with `add` in the LAST GRUB_CMDLINE_LINUX assignment (appended when there is
    none) and the same keys taken out of every GRUB_CMDLINE_LINUX[_DEFAULT] assignment. Refuses a line
    it cannot rewrite exactly (shell expansions, continuation) rather than guessing."""
    lines = text.split("\n")
    keys = set(drop_keys) | {key_of(t) for t in add}
    last = None
    for i, ln in enumerate(lines):
        if ln.startswith("GRUB_CMDLINE_LINUX"):
            m = _LINE.match(ln)
            if not m or ln.rstrip().endswith("\\"):
                raise StepError("cannot rewrite %r in %s: edit it by hand" % (ln, GRUB_DEFAULTS))
            var, val = m.group(1), next(g for g in (m.group(2), m.group(3), m.group(4)) if g is not None)
            if var == "GRUB_CMDLINE_LINUX":
                last = i
            if "$" in val or "`" in val:
                if any(k in val for k in keys) or (add and var == "GRUB_CMDLINE_LINUX"):
                    raise StepError("%s uses a shell expansion: edit it by hand" % var)
                continue
            new = edit_tokens(val.split(), drop_keys=keys)
            if new != val.split():
                lines[i] = '%s="%s"%s' % (var, " ".join(new), (" " + m.group(5)) if m.group(5) else "")
    if add:
        if last is None:
            if lines and lines[-1] == "":
                lines.insert(len(lines) - 1, 'GRUB_CMDLINE_LINUX=""')
                last = len(lines) - 2
            else:
                lines.append('GRUB_CMDLINE_LINUX=""')
                last = len(lines) - 1
        m = _LINE.match(lines[last])
        if "$" in lines[last] or "`" in lines[last]:
            raise StepError("GRUB_CMDLINE_LINUX uses a shell expansion: edit it by hand")
        val = next(g for g in (m.group(2), m.group(3), m.group(4)) if g is not None)
        lines[last] = 'GRUB_CMDLINE_LINUX="%s"%s' % (" ".join(edit_tokens(val.split(), add=add)),
                                                     (" " + m.group(5)) if m.group(5) else "")
    return "\n".join(lines)


# ─── run ───────────────────────────────────────────────────────────────────────────────────────────
def say(msg):
    print(msg, flush=True)


def _run_cmd(argv, check=True, timeout=600, desc=None):
    say("$ " + " ".join(argv))
    p = subprocess.run(argv, timeout=timeout, stdout=sys.stdout, stderr=subprocess.STDOUT)
    if check and p.returncode != 0:
        raise StepError("%s failed (rc=%d)" % (desc or argv[0], p.returncode))
    return p.returncode


def _write_with_backup(path, content):
    if os.path.exists(path):
        bak = "%s.bak.%s.%s" % (path, KIND, time.strftime("%Y%m%d-%H%M%S"))
        shutil.copy2(path, bak)
        say("backup: %s" % bak)
    tmp = path + ".tmp-" + KIND
    with open(tmp, "w") as fh:
        fh.write(content)
    if os.path.exists(path):
        shutil.copymode(path, tmp)
    os.replace(tmp, path)


def _set_cmdline(f, add, drop_keys):
    """Writes the configured command line (step `cmdline`). Returns True when a file changed."""
    if f["bootloader"] == "systemd-boot":
        cur = open(KERNEL_CMDLINE).read().split() if os.path.exists(KERNEL_CMDLINE) else []
        new = edit_tokens(cur, add=add, drop_keys=drop_keys)
        if new == cur:
            say("%s: unchanged" % KERNEL_CMDLINE)
            return False
        _write_with_backup(KERNEL_CMDLINE, " ".join(new) + "\n")
        say("%s: %s" % (KERNEL_CMDLINE, " ".join(new)))
        return True
    try:
        cur = open(GRUB_DEFAULTS).read()
    except OSError as e:
        raise StepError("%s unreadable: %s" % (GRUB_DEFAULTS, e))
    new = edit_grub_defaults(cur, add=add, drop_keys=drop_keys)
    if new == cur:
        say("%s: unchanged" % GRUB_DEFAULTS)
        return False
    _write_with_backup(GRUB_DEFAULTS, new)
    for ln in new.split("\n"):
        if ln.startswith("GRUB_CMDLINE_LINUX"):
            say("%s: %s" % (GRUB_DEFAULTS, ln))
    return True


def _regenerate(f, probe, want, gone_keys=()):
    """Step `bootloader`: regenerate, then read back what the next boot gets."""
    if f["bootloader"] == "systemd-boot":
        _run_cmd(["proxmox-boot-tool", "refresh"], desc="proxmox-boot-tool refresh")
        return
    _run_cmd(["update-grub"], desc="update-grub")
    f2 = gather_facts(probe)
    if not f2["grub_cfg"]:
        raise StepError("no linux entry found in the 10_linux section of %s" % GRUB_CFG)
    for ln in f2["grub_cfg"]:
        miss = [t for t in want if t not in ln]
        left = [t for t in ln if key_of(t) in gone_keys]
        if miss or left:
            raise StepError("%s entry %s: %s (an /etc/default/grub.d/*.cfg file may override "
                            "GRUB_CMDLINE_LINUX)" % (GRUB_CFG, ln[1] if len(ln) > 1 else "?",
                                                     "missing " + " ".join(miss) if miss else
                                                     "still has " + " ".join(left)))
    say("%s: %d entries carry %s" % (GRUB_CFG, len(f2["grub_cfg"]), " ".join(want) or "none of ours"))


def run(probe=live_probe):
    say("== bobi %s host driver %s ==" % (KIND, SCRIPT_VERSION))
    if os.geteuid() != 0:
        say("ERROR: must run as root")
        return 1
    f = gather_facts(probe)
    plan = decide(f)
    say("state: %s (%s) %s" % (plan["status"], plan["code"], json.dumps(plan["params"], sort_keys=True)))
    if plan["status"] == "refused":
        say("REFUSED: %s - nothing was changed" % plan["code"])
        return 1
    if plan["status"] == "pending_reboot":
        say("nothing to do: %s is on the boot line, reboot the node to apply it" % " ".join(plan["tokens"]))
        return EXIT_REBOOT
    if plan["status"] != "install":
        say("nothing to do (%s)" % plan["code"])
        return EXIT_OK
    try:
        for i, name in enumerate(plan["steps"], 1):
            say("")
            say("[step %d/%d] %s" % (i, len(plan["steps"]), name))
            if name == "cmdline":
                _set_cmdline(f, plan["tokens"], ())
            else:
                _regenerate(f, probe, plan["tokens"])
    except StepError as e:
        say("FAILED: %s" % e)
        return 1
    except subprocess.TimeoutExpired:
        say("FAILED: timeout")
        return 1
    say("")
    say("DONE - reboot the node: %s takes effect when the driver loads" % " ".join(plan["tokens"]))
    return EXIT_REBOOT


def revert(probe=live_probe):
    """Takes every parameter of DRIVERS back out of the configured boot line."""
    say("== bobi %s host driver %s : revert ==" % (KIND, SCRIPT_VERSION))
    if os.geteuid() != 0:
        say("ERROR: must run as root")
        return 1
    f = gather_facts(probe)
    if not f["bootloader"]:
        say("REFUSED: no_bootloader - nothing was changed")
        return 1
    keys = sorted({key_of(token(m)) for m in DRIVERS})
    try:
        changed = _set_cmdline(f, (), keys)
        if changed or (f["bootloader"] == "grub" and any(key_of(t) in keys for ln in f["grub_cfg"] for t in ln)):
            _regenerate(f, probe, (), gone_keys=keys)
    except StepError as e:
        say("FAILED: %s" % e)
        return 1
    if any(key_of(t) in keys for t in f["cmdline"]):
        say("DONE - reboot the node to boot without them")
        return EXIT_REBOOT
    say("DONE")
    return EXIT_OK


def main(argv):
    cmd = argv[1] if len(argv) > 1 else "state"
    if cmd == "state":
        print(json.dumps(state(), sort_keys=True))
        return 0
    if cmd == "run":
        return run()
    if cmd == "revert":
        return revert()
    print("usage: irq_managed.py state|run|revert", file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
